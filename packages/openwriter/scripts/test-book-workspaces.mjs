// Synthetic fixtures only. Conversion, guidance and review exercise real services.
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const fixture = mkdtempSync(join(tmpdir(), 'ow-book-workspace-'));
process.env.OW_DATA_DIR = fixture;
const helpers = await import('../dist/server/helpers.js');
helpers.ensureDataDir(); helpers.ensureWorkspacesDir();
const docs = await import('../dist/server/documents.js');
const ws = await import('../dist/server/workspaces.js');
const state = await import('../dist/server/state.js');
const { parseMarkdownContent } = await import('../dist/server/compact.js');
const { readFrontmatter } = await import('../dist/server/backlinks.js');
const { createOutline } = await import('../dist/server/manuscript/outline-info.js');
const { createRevision } = await import('../dist/server/document-revisions.js');
const { configureBookWorkspace, createWorkspaceOutline, createWorkspaceBrief, bookContexts } = await import('../dist/server/book-workspaces.js');
const { bookWorkspaceView } = await import('../dist/server/book-workspace-model.js');
const { TOOL_REGISTRY, appendDocGuidance } = await import('../dist/server/mcp.js');
const tool = name => TOOL_REGISTRY.find(t => t.name === name);
const agent = async (session, name, args) => appendDocGuidance(session, args, await tool(name).handler(args));
const extra = r => r.content.slice(1).map(c => c.text).join('\n');
const bytes = doc => readFileSync(join(helpers.getDataDir(), doc.filename), 'utf8');
const write = (doc, body) => {
  const fm = readFrontmatter(doc.filename);
  state.writeResolvedDocFile(doc.filename, { type: 'doc', content: parseMarkdownContent(body) }, doc.title, fm.data);
};
const placed = (workspace, title, body, container = null) => {
  const doc = docs.createDocumentFile(title);
  write(doc, body); ws.addDoc(workspace, container, doc.filename, title); return doc;
};
try {
  const workspace = ws.createWorkspace({ title: 'Synthetic garden book' }).filename;
  const folder = ws.addContainerToWorkspace(workspace, null, 'Beats').containerId;
  const source = placed(workspace, 'Garden source', 'The fictional garden has three gates.', folder);
  const direction = placed(workspace, 'Audience', 'Written for beginning gardeners.');
  const outline = createOutline('Garden outline', workspace);
  write(outline, `## First chapter\n\n[Garden](doc:${source.docId})`);
  const manuscript = createRevision(outline.docId);
  const brief = placed(workspace, 'Garden brief', `Describe the garden plainly.\n\nAudience: [Reader](doc:${direction.docId})`);
  docs.switchDocument(source.filename);
  const pending = await tool('write_to_pad').handler({ docId: source.docId, changes: [{ operation: 'insert', afterNodeId: 'end', content: 'A proposed fourth gate.' }] });
  assert(!/^Error/.test(pending.content[0].text));
  const before = new Map([source, direction, outline, manuscript, brief].map(d => [d.filename, bytes(d)]));
  const tree = JSON.stringify(ws.getWorkspace(workspace).root);
  const pendingBefore = state.countPending((await import('../dist/server/pending-overlay.js')).loadDocFromDisk(source.filename).document.content);
  const converted = configureBookWorkspace(workspace, { workspaceType: 'book', briefDocId: brief.docId });
  assert.equal(converted.book.outlineDocId, outline.docId);
  assert.equal(converted.book.manuscriptDocId, manuscript.docId);
  assert.equal(JSON.stringify(converted.root), tree);
  for (const [file, body] of before) assert.equal(readFileSync(join(helpers.getDataDir(), file), 'utf8'), body, file);
  assert.equal(state.countPending((await import('../dist/server/pending-overlay.js')).loadDocFromDisk(source.filename).document.content), pendingBefore);
  assert.equal(bookWorkspaceView(converted, docs.listDocuments()).manuscript.docId, manuscript.docId);
  assert.equal(createWorkspaceOutline(workspace).docId, outline.docId, 'idempotent creation reuses selected documents');
  assert.equal(createWorkspaceBrief(workspace).docId, brief.docId);
  console.log('PASS: conversion preserves all text, tree placement, pending review and existing book identity');

  const general = configureBookWorkspace(workspace, { workspaceType: 'general' });
  assert.deepEqual(general.book, converted.book);
  assert.equal(bookContexts(source.docId).length, 0);
  configureBookWorkspace(workspace, { workspaceType: 'book' });
  const other = ws.createWorkspace({ title: 'Other synthetic book' }).filename;
  const foreign = createOutline('Other outline', other);
  const saved = JSON.stringify(ws.getWorkspace(workspace));
  assert.throws(() => configureBookWorkspace(workspace, { outlineDocId: foreign.docId }), /belongs/);
  assert.equal(JSON.stringify(ws.getWorkspace(workspace)), saved, 'invalid attachments do not partially mutate');
  const alternate = createOutline('Alternate outline', workspace);
  assert.throws(() => configureBookWorkspace(workspace, { outlineDocId: alternate.docId, manuscriptDocId: manuscript.docId }), /built from/);
  const ambiguous = ws.createWorkspace({ title: 'Ambiguous synthetic book' }).filename;
  ws.addDoc(ambiguous, null, outline.filename, outline.title); ws.addDoc(ambiguous, null, alternate.filename, alternate.title);
  assert.equal(configureBookWorkspace(ambiguous, { workspaceType: 'book' }).book.outlineDocId, undefined);
  configureBookWorkspace(ambiguous, { workspaceType: 'general' });
  console.log('PASS: reversible type and explicit choices for foreign, mismatched and ambiguous attachments');

  let g = extra(await agent('first', 'get_metadata', { docId: manuscript.docId }));
  assert.match(g, /## Book workspace/); assert.match(g, /## Book manuscript/); assert.match(g, /Describe the garden plainly/);
  assert.match(extra(await agent('first', 'get_metadata', { docId: manuscript.docId })), /unchanged/);
  assert.match(extra(await agent('variant-context', 'get_item_context', { docId: manuscript.docId, workspaceFile: workspace })), /Describe the garden plainly/);
  configureBookWorkspace(workspace, { workspaceType: 'general' });
  assert.match(extra(await agent('first', 'get_metadata', { docId: manuscript.docId })), /no longer has a Book workspace context/);
  configureBookWorkspace(workspace, { workspaceType: 'book' });
  write(direction, 'Written for experienced gardeners.');
  g = extra(await agent('first', 'get_metadata', { docId: source.docId }));
  assert.match(g, /context changed/); assert.doesNotMatch(g, /## Book workspace/);
  write(brief, `Use precise garden names.\n\n[Audience](doc:${direction.docId})`);
  g = extra(await agent('first', 'get_metadata', { docId: manuscript.docId }));
  assert.match(g, /context changed/); assert.match(g, /Use precise garden names/);
  await tool('write_to_pad').handler({ docId: brief.docId, changes: [{ operation: 'insert', afterNodeId: 'end', content: 'UNAPPROVED_DIRECTION' }] });
  g = extra(await agent('second', 'get_metadata', { docId: source.docId }));
  assert.match(g, /proposed brief changes await review/); assert.doesNotMatch(g, /UNAPPROVED_DIRECTION/);
  const proposal = (await import('../dist/server/pending-overlay.js')).loadDocFromDisk(brief.filename).document;
  assert(state.countPending(proposal.content) > 0);
  docs.batchResolve([brief.filename], 'accept');
  g = extra(await agent('second', 'get_metadata', { docId: source.docId }));
  assert.match(g, /context changed/); assert.match(g, /UNAPPROVED_DIRECTION/);
  docs.switchDocument(brief.filename);
  state.updateDocument({ type: 'doc', content: parseMarkdownContent('Human direction before the save timer.') });
  assert.equal(bookContexts(source.docId)[0].briefText, 'Human direction before the save timer.');
  state.save(); docs.switchDocument(source.filename);
  write(brief, `Use precise garden names.\n\n[Audience](doc:${direction.docId})`);
  await tool('get_metadata').handler({ docId: source.docId });
  assert.match(extra(await agent('internal-not-consumed', 'get_metadata', { docId: source.docId })), /## Book workspace/);
  console.log('PASS: automatic session guidance, changed brief/source refresh and accepted-only authority');

  ws.addDoc(other, null, source.filename, source.title);
  configureBookWorkspace(other, { workspaceType: 'book' });
  g = extra(await agent('shared', 'get_metadata', { docId: source.docId }));
  assert.match(g, /multiple book workspaces/); assert.doesNotMatch(g, /Use precise garden names/);
  g = extra(await agent('shared', 'get_item_context', { docId: source.docId, workspaceFile: workspace }));
  assert.match(g, /Use precise garden names/);
  const empty = ws.createWorkspace({ title: 'New synthetic book' }).filename;
  configureBookWorkspace(empty, { workspaceType: 'book' });
  const newOutline = createOutline('Selected-source outline', empty);
  assert.equal(ws.getWorkspace(empty).book.outlineDocId, newOutline.docId, 'selection-based outline creation fills the pin');
  const newBrief = createWorkspaceBrief(empty);
  assert.equal(createWorkspaceBrief(empty).docId, newBrief.docId);
  assert.match(extra(await agent('workspace-read', 'get_workspace_structure', { filename: empty })), /## Book workspace/);
  console.log('PASS: shared-book ambiguity, explicit context, selection flow and idempotent brief scaffold');

  const fresh = ws.createWorkspace({ title: 'Agent-started book' }).filename;
  const setup = await agent('starter', 'configure_book_workspace', { workspaceFile: fresh, workspaceType: 'book', createBrief: true, createOutline: true });
  const made = JSON.parse(setup.content[0].text).book;
  assert(made.briefDocId && made.outlineDocId, 'setup attaches a new brief and outline');
  g = extra(setup);
  assert.match(g, /## Book workspace/); assert.match(g, /## OpenWriter book method/); assert.match(g, /Workflow: Guided/); assert.match(g, /Voice: not learned yet/);
  g = extra(await agent('starter', 'get_metadata', { docId: made.briefDocId }));
  assert.match(g, /## Attached book brief/); assert.match(g, /Learn my voice from this/); assert.doesNotMatch(g, /Voice:/, 'an unchanged voice status is not repeated');
  assert.match((await tool('read_pad').handler({ docId: made.briefDocId })).content[0].text, /How we work/, 'the brief has a place for how the writer wants to work');
  assert.match((await tool('get_voice').handler({ about: 'the opening chapter' })).content[0].text, /no voice to write in yet/);
  await agent('starter', 'configure_book_workspace', { workspaceFile: fresh, createBrief: true, createOutline: true });
  assert.deepEqual(ws.getWorkspace(fresh).book, { ...ws.getWorkspace(fresh).book, briefDocId: made.briefDocId, outlineDocId: made.outlineDocId }, 'a second setup keeps the attached brief and outline');
  console.log('PASS: an agent starts a book in one call and gets the book method and voice status');

  configureBookWorkspace(fresh, { workflow: 'custom' });
  g = extra(await agent('starter', 'get_metadata', { docId: made.briefDocId }));
  assert.match(g, /context changed/); assert.match(g, /Workflow: Custom/); assert.doesNotMatch(g, /book-method v/, 'the method leaves the guidance list');
  g = extra(await agent('leader', 'get_metadata', { docId: made.outlineDocId }));
  assert.match(g, /## Book workspace/); assert.doesNotMatch(g, /## OpenWriter book method/);
  assert.throws(() => configureBookWorkspace(fresh, { workflow: 'other' }));
  configureBookWorkspace(fresh, { workflow: 'guided' });
  assert.match(extra(await agent('leader', 'get_metadata', { docId: made.outlineDocId })), /## OpenWriter book method/);
  console.log('PASS: the writer switches between the Guided and Custom workflows, and the agent hears it at its next step');
} finally {
  state.cancelDebouncedSave(); state.clearAllCaches(); rmSync(fixture, { recursive: true, force: true });
}
